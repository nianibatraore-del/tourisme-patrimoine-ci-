-- 16. VUES

CREATE OR REPLACE VIEW v_sites_complets AS
SELECT
 s.id_site,
 s.nom_site,
 s.localite,
 STRING_AGG(DISTINCT z.nom_zone, ', ') AS zones,
 STRING_AGG(DISTINCT a.nom_activite, ', ' ORDER BY a.nom_activite) AS activites,
 s.categorie,
 s.description,
 s.horaires,
 s.tarifs_details,
 s.guide_obligatoire,
 s.est_fiche_majeure,
 s.classe_unesco
FROM sites_touristiques s
LEFT JOIN site_zone sz ON sz.id_site=s.id_site
LEFT JOIN zones_geographiques z ON z.id_zone=sz.id_zone
LEFT JOIN site_activite sa ON sa.id_site=s.id_site
LEFT JOIN activites a ON a.id_activite=sa.id_activite
GROUP BY s.id_site;

CREATE VIEW v_expressions_culturelles AS
SELECT
 e.id_element,
 e.nom_element,
 e.type_element,
 e.description,
 STRING_AGG(DISTINCT p.nom_peuple, ', ') AS peuples,
 STRING_AGG(DISTINCT z.nom_zone, ', ') AS zones
FROM elements_culturels e
LEFT JOIN element_peuple ep ON ep.id_element=e.id_element
LEFT JOIN peuples p ON p.id_peuple=ep.id_peuple
LEFT JOIN element_zone ez ON ez.id_element=e.id_element
LEFT JOIN zones_geographiques z ON z.id_zone=ez.id_zone
GROUP BY e.id_element;

CREATE VIEW v_annuaire_hebergements AS
SELECT
 h.id_hebergement,
 h.nom_etablissement,
 h.ville_localite,
 z.nom_zone,
 h.type_hebergement,
 h.tarif_min_fcfa,
 h.tarif_max_fcfa,
 h.tarif_texte,
 h.telephone,
 h.email,
 h.site_web
FROM hebergements h
JOIN zones_geographiques z ON z.id_zone=h.id_zone;

