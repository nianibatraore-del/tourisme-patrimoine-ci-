DROP VIEW IF EXISTS v_annuaire_hebergements, v_expressions_culturelles, v_sites_complets;
DROP TABLE IF EXISTS prestataires_guides, hebergements, patrimoine_site, patrimoine_unesco,
 evenement_peuple, evenement_zone, evenements_festivals, pagne_aire, pagne_zone,
 pagnes_traditionnels, element_zone, element_peuple, elements_culturels,
 site_activite, activites, site_zone, sites_touristiques, peuples,
 aires_culturelles, zones_geographiques CASCADE;
DROP TYPE IF EXISTS activity_type, provider_type, accommodation_type, heritage_type,
 cultural_type, site_category, zone_type CASCADE;

BEGIN;
SET client_encoding = 'UTF8';

-- 1. TYPES

CREATE TYPE zone_type AS ENUM ('District autonome', 'Région');

CREATE TYPE site_category AS ENUM (
 'Monument / Architecture',
 'Musée / Patrimoine',
 'Parc / Réserve naturelle',
 'Plage / Lagune / Cascade',
 'Site archéologique / Sacré',
 'Village artisanal / Chefferie',
 'Loisirs / Écotourisme'
);

CREATE TYPE cultural_type AS ENUM (
 'Masque', 'Danse', 'Instrument de musique', 'Pratique rituelle'
);

CREATE TYPE heritage_type AS ENUM (
 'Patrimoine mondial naturel',
 'Patrimoine mondial culturel',
 'Patrimoine culturel immatériel'
);

CREATE TYPE accommodation_type AS ENUM (
 'Hôtel', 'Résidence hôtelière', 'Lodge / Écolodge',
 'Auberge / Guesthouse', 'Camping'
);

CREATE TYPE provider_type AS ENUM (
 'Guide local', 'Guide national',
 'Agence de voyages / Tour-opérateur',
 'Plateforme / Institution'
);

CREATE TYPE activity_type AS ENUM (
 'Nature et découverte',
 'Activités nautiques et balnéaires',
 'Aventure et loisirs',
 'Culture et artisanat'
);

-- 2. TABLES

CREATE TABLE zones_geographiques (
 id_zone INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nom_zone VARCHAR(150) NOT NULL UNIQUE,
 type_zone zone_type NOT NULL DEFAULT 'Région',
 grande_aire VARCHAR(100),
 description TEXT
);

CREATE TABLE aires_culturelles (
 id_aire INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nom_aire VARCHAR(100) NOT NULL UNIQUE,
 description TEXT
);

CREATE TABLE peuples (
 id_peuple INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_aire INTEGER NOT NULL REFERENCES aires_culturelles(id_aire),
 nom_peuple VARCHAR(100) NOT NULL UNIQUE,
 sous_groupes TEXT,
 pratiques_notables TEXT
);

CREATE TABLE sites_touristiques (
 id_site INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nom_site VARCHAR(180) NOT NULL,
 localite VARCHAR(150),
 categorie site_category NOT NULL,
 description TEXT NOT NULL,
 horaires TEXT,
 tarifs_details TEXT,
 guide_obligatoire BOOLEAN,
 infos_guide_acces TEXT,
 est_fiche_majeure BOOLEAN DEFAULT FALSE,
 classe_unesco BOOLEAN DEFAULT FALSE
);

CREATE TABLE site_zone (
 id_site INTEGER NOT NULL REFERENCES sites_touristiques(id_site) ON DELETE CASCADE,
 id_zone INTEGER NOT NULL REFERENCES zones_geographiques(id_zone) ON DELETE CASCADE,
 PRIMARY KEY (id_site,id_zone)
);

CREATE TABLE activites (
 id_activite INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nom_activite VARCHAR(150) NOT NULL UNIQUE,
 categorie activity_type NOT NULL
);

CREATE TABLE site_activite (
 id_site INTEGER REFERENCES sites_touristiques(id_site) ON DELETE CASCADE,
 id_activite INTEGER REFERENCES activites(id_activite) ON DELETE CASCADE,
 PRIMARY KEY (id_site,id_activite)
);

CREATE TABLE elements_culturels (
 id_element INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nom_element VARCHAR(150) NOT NULL,
 type_element cultural_type NOT NULL,
 sous_categorie VARCHAR(100),
 description TEXT NOT NULL
);

CREATE TABLE element_peuple (
 id_element INTEGER REFERENCES elements_culturels(id_element) ON DELETE CASCADE,
 id_peuple INTEGER REFERENCES peuples(id_peuple) ON DELETE CASCADE,
 PRIMARY KEY (id_element,id_peuple)
);

CREATE TABLE element_zone (
 id_element INTEGER REFERENCES elements_culturels(id_element) ON DELETE CASCADE,
 id_zone INTEGER REFERENCES zones_geographiques(id_zone) ON DELETE CASCADE,
 PRIMARY KEY (id_element,id_zone)
);

CREATE TABLE pagnes_traditionnels (
 id_pagne INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nom_pagne VARCHAR(150) NOT NULL,
 appellations_locales TEXT,
 matiere_technique TEXT,
 centres_production TEXT,
 caracteristiques TEXT NOT NULL
);

CREATE TABLE pagne_zone (
 id_pagne INTEGER REFERENCES pagnes_traditionnels(id_pagne) ON DELETE CASCADE,
 id_zone INTEGER REFERENCES zones_geographiques(id_zone) ON DELETE CASCADE,
 PRIMARY KEY (id_pagne,id_zone)
);

CREATE TABLE pagne_aire (
 id_pagne INTEGER REFERENCES pagnes_traditionnels(id_pagne) ON DELETE CASCADE,
 id_aire INTEGER REFERENCES aires_culturelles(id_aire) ON DELETE CASCADE,
 PRIMARY KEY (id_pagne,id_aire)
);

CREATE TABLE evenements_festivals (
 id_evenement INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nom_evenement VARCHAR(160) NOT NULL,
 localite VARCHAR(150),
 periodicite VARCHAR(120),
 description TEXT NOT NULL,
 restrictions_acces TEXT
);

CREATE TABLE evenement_zone (
 id_evenement INTEGER REFERENCES evenements_festivals(id_evenement) ON DELETE CASCADE,
 id_zone INTEGER REFERENCES zones_geographiques(id_zone) ON DELETE CASCADE,
 PRIMARY KEY (id_evenement,id_zone)
);

CREATE TABLE evenement_peuple (
 id_evenement INTEGER REFERENCES evenements_festivals(id_evenement) ON DELETE CASCADE,
 id_peuple INTEGER REFERENCES peuples(id_peuple) ON DELETE CASCADE,
 PRIMARY KEY (id_evenement,id_peuple)
);

CREATE TABLE patrimoine_unesco (
 id_unesco INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nom_inscription VARCHAR(220) NOT NULL,
 type_patrimoine heritage_type NOT NULL,
 annee_inscription SMALLINT,
 annee_extension SMALLINT,
 numero_dossier VARCHAR(50),
 details TEXT NOT NULL
);

CREATE TABLE patrimoine_site (
 id_unesco INTEGER REFERENCES patrimoine_unesco(id_unesco) ON DELETE CASCADE,
 id_site INTEGER REFERENCES sites_touristiques(id_site) ON DELETE CASCADE,
 PRIMARY KEY (id_unesco,id_site)
);

CREATE TABLE hebergements (
 id_hebergement INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_zone INTEGER NOT NULL REFERENCES zones_geographiques(id_zone),
 nom_etablissement VARCHAR(180) NOT NULL,
 ville_localite VARCHAR(120),
 type_hebergement accommodation_type NOT NULL DEFAULT 'Hôtel',
 tarif_min_fcfa INTEGER CHECK (tarif_min_fcfa >= 0),
 tarif_max_fcfa INTEGER CHECK (tarif_max_fcfa >= 0),
 tarif_texte TEXT,
 telephone VARCHAR(100),
 email VARCHAR(180),
 site_web VARCHAR(200),
 CHECK (tarif_min_fcfa IS NULL OR tarif_max_fcfa IS NULL
        OR tarif_max_fcfa >= tarif_min_fcfa)
);

CREATE TABLE prestataires_guides (
 id_prestataire INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_zone INTEGER REFERENCES zones_geographiques(id_zone),
 nom_structure_ou_guide VARCHAR(180) NOT NULL,
 type_prestataire provider_type NOT NULL,
 zone_intervention VARCHAR(180) NOT NULL,
 langues VARCHAR(150),
 specialite TEXT,
 telephone VARCHAR(100),
 email VARCHAR(180),
 site_web_ou_reseau VARCHAR(200)
);

